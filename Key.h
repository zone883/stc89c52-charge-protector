#ifndef __KEY_H__
#define __KEY_H__

#include <REGX52.H>

/* ------------------------------------------------------------------
 * 独立按键(非阻塞扫描)
 *
 * 硬件: 江协科技/普中开发板 K1~K4, 按下为低电平
 *       实际接法 K1=P3.1  K2=P3.0  K3=P3.2  K4=P3.3
 *       (不是 P3.0~P3.3 顺序! 映射表见 Key.c 顶部, 一行就能改)
 *
 * 事件返回格式:  低 4 位 = 键号(1~4), 0 表示没有事件
 *                bit7    = 1 表示长按(按住 >= 1s), 0 表示短按(松手时上报)
 * ------------------------------------------------------------------ */
#define KEY_LONG_FLAG 0x80

void Key_Update(void);                   /* 放在主循环里, 约每 10ms 调用一次 */
unsigned char Key_GetEvent(void);        /* 取一个按键事件(取完自动清除) */
unsigned char Key_GetDown(void);         /* 当前按住的键掩码(bit0~bit3 = K1~K4) */

#endif
